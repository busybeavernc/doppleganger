"""Render the picture the Doppleganger camera shows while the app isn't running
(a neutral "Camera starting..." - viewers in the meeting can see it),
and write it as a C header compiled into the camera driver.

    python driver/make_placeholder.py <out.h> [preview.png]

640x360, stored as a bottom-up 24-bit BGR DIB; the driver scales it to the camera size.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

W, H = 640, 360
HERE = os.path.dirname(os.path.abspath(__file__))


def font(px: int, bold: bool = False):
    names = (["segoeuib.ttf", "seguisb.ttf", "arialbd.ttf"] if bold else ["segoeui.ttf", "arial.ttf"]) + [
        "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf" if bold else "/usr/share/fonts/opentype/inter/Inter-Regular.otf",
        "DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"]
    for n in names:
        try:
            return ImageFont.truetype(n, px)
        except OSError:
            continue
    return ImageFont.load_default()


def render() -> Image.Image:
    """Deliberately generic - meeting participants can see this, so it must not name the app.
    It looks like any webcam warming up."""
    img = Image.new("RGB", (W, H), (16, 18, 22))
    d = ImageDraw.Draw(img)
    f = font(15)
    text = "Camera starting…"
    d.text(((W - d.textlength(text, font=f)) / 2, H / 2 - 9), text, font=f, fill=(110, 116, 128))
    return img


def main(out_h: str, preview: str | None = None) -> None:
    img = render()
    if preview:
        img.save(preview)
    rows = img.transpose(Image.FLIP_TOP_BOTTOM).tobytes("raw", "BGR")  # bottom-up BGR, stride 1920 (4-aligned)
    with open(out_h, "w", encoding="ascii") as f:
        f.write("// Generated by driver/make_placeholder.py - the Doppleganger camera's 'not running' picture.\n")
        f.write("#pragma once\n#include <cstdint>\n#include <cstring>\n\n")
        f.write(f"static const int kPlaceholderW = {W}, kPlaceholderH = {H};\n")
        f.write("static const std::uint8_t kPlaceholder[] = {\n")
        for i in range(0, len(rows), 32):
            f.write(",".join(str(b) for b in rows[i:i + 32]) + ",\n")
        f.write("};\n\n")
        f.write("""// Scale the placeholder into a camera frame (bottom-up 24-bit DIB with 4-byte row padding).
static inline void dopplegangerPlaceholder(std::uint8_t* dst, int w, int h)
{
    if (!dst || w <= 0 || h <= 0) return;
    const int stride = (w * 3 + 3) & ~3;
    for (int y = 0; y < h; y++)
    {
        const int sy = y * kPlaceholderH / h;
        const std::uint8_t* src = kPlaceholder + (std::size_t)sy * kPlaceholderW * 3;
        std::uint8_t* row = dst + (std::size_t)y * stride;
        for (int x = 0; x < w; x++)
        {
            const int sx = x * kPlaceholderW / w;
            std::memcpy(row + x * 3, src + sx * 3, 3);
        }
    }
}
""")
    print(f"wrote {out_h} ({len(rows)} bytes of image)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
